const dicts = { en, bn };
export type Key = keyof Dict;

export const useLang = create<{ lang: Lang; setLang: (l: Lang) => void }>((set) => ({
  lang: 'en',
  setLang: (lang) => set({ lang }),
}));

export function useT() {
  const lang = useLang((s) => s.lang);
  const d = dicts[lang];
  return Object.assign((k: Key) => d[k], { lang });
}

const MONTHS = { en: ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'], bn: ['জানু', 'ফেব্রু', 'মার্চ', 'এপ্রি', 'মে', 'জুন', 'জুলা', 'আগ', 'সেপ্টে', 'অক্টো', 'নভে', 'ডিসে'] };
const DAYS = { en: ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'], bn: ['রবি', 'সোম', 'মঙ্গল', 'বুধ', 'বৃহঃ', 'শুক্র', 'শনি'] };
const MONTHS_LONG = { en: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'], bn: ['জানুয়ারি', 'ফেব্রুয়ারি', 'মার্চ', 'এপ্রিল', 'মে', 'জুন', 'জুলাই', 'আগস্ট', 'সেপ্টেম্বর', 'অক্টোবর', 'নভেম্বর', 'ডিসেম্বর'] };

export const parts = (date: string) => { const [y, m, d] = date.split('-').map(Number); return { y, m, d, wd: new Date(Date.UTC(y, m - 1, d)).getUTCDay() }; };
export const dayName = (lang: Lang, wd: number) => DAYS[lang][wd];
export const monthName = (lang: Lang, m: number) => MONTHS_LONG[lang][m - 1];
/** 'Mon 23 Nov' */
export function shortDate(lang: Lang, date: string) {
  const p = parts(date);
  return `${DAYS[lang][p.wd]} ${p.d} ${MONTHS[lang][p.m - 1]}`;
}
