const dicts = { en, bn };
export type Key = keyof Dict;

export const useLang = create<{ lang: Lang }>(() => ({ lang: 'en' }));

export async function loadLang() {
  const l = await storage.get('lang');
  if (l === 'en' || l === 'bn') useLang.setState({ lang: l });
}
export function setLang(lang: Lang) { useLang.setState({ lang }); void storage.set('lang', lang); }

export function useT() {
  const lang = useLang((s) => s.lang);
  const d = dicts[lang];
  return Object.assign((k: Key) => d[k], { lang });
}
